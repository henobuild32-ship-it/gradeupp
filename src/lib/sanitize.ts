/** Shapes the server-side user record for the client: no PIN, no password, no hashes. */
export function sanitizeSafeUser(user: any) {
  return {
    id: user.id,
    phone: user.phone,
    name: user.name,
    pseudo: user.pseudo,
    email: user.email,
    gender: user.gender,
    city: user.city,
    country: user.country,
    role: user.role,
    agentCode: user.agentCode,
    agentNumber: user.agentNumber,
    businessName: user.businessName,
    businessType: user.businessType,
    location: user.location,
    validationStatus: user.validationStatus,
    validationRejectReason: user.validationRejectReason,
    realBalance: user.realBalance,
    realBalanceFC: user.realBalanceFC,
    bonusBalance: user.bonusBalance,
    bonusBalanceFC: user.bonusBalanceFC,
    isVerified: user.isVerified,
    parentId: user.parentId,
    hasCompletedOnboarding: user.hasCompletedOnboarding,
    pinSet: Boolean(user.pin),
    biometricEnabled: Boolean(user.biometricEnabled),
    unlockMethod: user.unlockMethod || 'none',
    twoFactorEnabled: Boolean(user.twoFactorEnabled),
    referralCode: user.referralCode,
    photoUrl: user.photoUrl,
    authProvider: user.authProvider,
  };
}
