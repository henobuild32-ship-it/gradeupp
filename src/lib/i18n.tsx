// ─── I18n Context ────────────────────────────────────────────────
interface I18nContextType {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: (key: string, params?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextType>({
  language: 'fr',
  setLanguage: () => {},
  t: (key: string) => key,
});

// ─── Provider Component ─────────────────────────────────────────
export function I18nProvider({ children, language, setLanguage }: {
  children: React.ReactNode;
  language: Language;
  setLanguage: (lang: Language) => void;
}) {
  const activeLanguage: Language = language === 'en' ? 'en' : 'fr';

  useEffect(() => {
    document.documentElement.lang = activeLanguage;
    if (language !== activeLanguage) setLanguage(activeLanguage);
  }, [activeLanguage, language, setLanguage]);

  const t = useCallback((key: string, params?: Record<string, string | number>): string => {
    const dict = translations[activeLanguage];
    let text = dict[key] || homepageTranslations[activeLanguage][key] || key;

    if (params) {
      Object.entries(params).forEach(([k, v]) => {
        text = text.replace(`{${k}}`, String(v));
      });
    }

    return text;
  }, [activeLanguage]);

  const contextValue = useMemo(() => ({
    language: activeLanguage,
    setLanguage,
    t,
  }), [language, setLanguage, t]);

  return (
    <I18nContext.Provider value={contextValue}>
      {children}
    </I18nContext.Provider>
  );
}

// ─── Hook ────────────────────────────────────────────────────────
export function useTranslation() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error('useTranslation must be used within an I18nProvider');
  }
  return context;
}
